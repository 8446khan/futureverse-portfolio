import os
import sqlite3
import json
import psycopg

from app.db import TABLES

# Local SQLite database
SQLITE_PATH = os.path.join(os.path.dirname(__file__), "portfolio.db")

# PostgreSQL External Database URL
DATABASE_URL = os.getenv("MIGRATION_DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("MIGRATION_DATABASE_URL is missing. Set it in your terminal.")


def migrate():
    if not os.path.exists(SQLITE_PATH):
        raise FileNotFoundError(f"SQLite database not found: {SQLITE_PATH}")

    sqlite_db = sqlite3.connect(SQLITE_PATH)
    sqlite_db.row_factory = sqlite3.Row

    postgres_db = psycopg.connect(DATABASE_URL)

    try:
        with postgres_db.cursor() as cursor:
            for table in sorted(TABLES):
                cursor.execute(f"""
                    CREATE TABLE IF NOT EXISTS {table} (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        data TEXT NOT NULL,
                        created_at TEXT NOT NULL
                    )
                """)

            cursor.execute("""
                CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email
                ON users ((data::jsonb ->> 'email'))
            """)

            cursor.execute("""
                CREATE UNIQUE INDEX IF NOT EXISTS idx_profile_key
                ON profile ((data::jsonb ->> 'key'))
            """)

            postgres_db.commit()

            for table in sorted(TABLES):
                rows = sqlite_db.execute(
                    f"SELECT id, data, created_at FROM {table} ORDER BY id"
                ).fetchall()

                print(f"\nMigrating {table}: {len(rows)} records")

                for row in rows:
                    cursor.execute(
                        f"""
                        INSERT INTO {table} (id, data, created_at)
                        VALUES (%s, %s, %s)
                        ON CONFLICT (id) DO NOTHING
                        """,
                        (row["id"], row["data"], row["created_at"]),
                    )

            # Reset PostgreSQL identity counters after preserving IDs.
            for table in sorted(TABLES):
                cursor.execute(
                    f"""
                    SELECT setval(
                        pg_get_serial_sequence(%s, 'id'),
                        COALESCE((SELECT MAX(id) FROM {table}), 1),
                        EXISTS (SELECT 1 FROM {table})
                    )
                    """,
                    (table,),
                )

        postgres_db.commit()

        print("\nMigration completed successfully!")

    except Exception:
        postgres_db.rollback()
        raise

    finally:
        sqlite_db.close()
        postgres_db.close()


if __name__ == "__main__":
    migrate()
