import json
import os
import sqlite3

from datetime import datetime, timezone
from flask import current_app, g

TABLES = {
    "users",
    "profile",
    "projects",
    "skills",
    "experience",
    "certifications",
    "messages",
    "page_views",
}


def validate_table(table):
    if table not in TABLES:
        raise ValueError("Unknown table")


def is_postgres():
    return bool(current_app.config.get("DATABASE_URL"))


def get_db():
    if "db" not in g:
        if is_postgres():
            import psycopg
            from psycopg.rows import dict_row

            database_url = current_app.config["DATABASE_URL"]

            # Render PostgreSQL connection
            g.db = psycopg.connect(
                database_url, row_factory=dict_row, connect_timeout=10
            )

        else:
            path = current_app.config["DATABASE"]

            directory = os.path.dirname(path)
            if directory:
                os.makedirs(directory, exist_ok=True)

            g.db = sqlite3.connect(path, timeout=10)
            g.db.row_factory = sqlite3.Row
            g.db.execute("PRAGMA foreign_keys = ON")
            g.db.execute("PRAGMA journal_mode = WAL")
            g.db.execute("PRAGMA busy_timeout = 10000")

    return g.db


def execute(sql, params=()):
    connection = get_db()

    if is_postgres():
        sql = sql.replace("?", "%s")

    return connection.execute(sql, params)


def close_db(_error=None):
    connection = g.pop("db", None)

    if connection is not None:
        connection.close()


def init_db():
    db = get_db()

    for table in TABLES:
        if is_postgres():
            execute(f"""
                CREATE TABLE IF NOT EXISTS {table} (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    data TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )
            """)
        else:
            execute(f"""
                CREATE TABLE IF NOT EXISTS {table} (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    data TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )
            """)

    if is_postgres():
        execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email
            ON users ((data::jsonb ->> 'email'))
        """)

        execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_profile_key
            ON profile ((data::jsonb ->> 'key'))
        """)
    else:
        execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email
            ON users(json_extract(data, '$.email'))
        """)

        execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_profile_key
            ON profile(json_extract(data, '$.key'))
        """)

    db.commit()


def _decode(row):
    if row is None:
        return None

    item = json.loads(row["data"])
    item["id"] = str(row["id"])
    item.setdefault("created_at", row["created_at"])

    return item


def all_items(table, order_by="created_at", descending=True):
    validate_table(table)

    rows = execute(f"SELECT id, data, created_at FROM {table}").fetchall()

    items = [_decode(row) for row in rows]

    return sorted(
        items, key=lambda item: str(item.get(order_by, "")), reverse=descending
    )


def find_one(table, **criteria):
    validate_table(table)

    return next(
        (
            item
            for item in all_items(table)
            if all(item.get(key) == value for key, value in criteria.items())
        ),
        None,
    )


def insert(table, item):
    validate_table(table)

    payload = dict(item)
    created = payload.setdefault("created_at", datetime.now(timezone.utc).isoformat())

    if is_postgres():
        cursor = execute(
            f"""
            INSERT INTO {table} (data, created_at)
            VALUES (?, ?)
            RETURNING id
            """,
            (json.dumps(payload, ensure_ascii=False), str(created)),
        )
        item_id = cursor.fetchone()["id"]
    else:
        cursor = execute(
            f"""
            INSERT INTO {table} (data, created_at)
            VALUES (?, ?)
            """,
            (json.dumps(payload, ensure_ascii=False), str(created)),
        )
        item_id = cursor.lastrowid

    get_db().commit()

    return get(table, item_id)


def get(table, item_id):
    validate_table(table)

    try:
        item_id = int(item_id)
    except (TypeError, ValueError):
        return None

    row = execute(
        """
        SELECT id, data, created_at
        FROM """
        + table
        + """
        WHERE id = ?
        """,
        (item_id,),
    ).fetchone()

    return _decode(row)


def update(table, item_id, changes):
    validate_table(table)

    existing = get(table, item_id)

    if not existing:
        return None

    existing.pop("id", None)
    existing.update(changes)

    execute(
        f"""
        UPDATE {table}
        SET data = ?
        WHERE id = ?
        """,
        (json.dumps(existing, ensure_ascii=False), int(item_id)),
    )

    get_db().commit()

    return get(table, item_id)


def delete(table, item_id):
    validate_table(table)

    try:
        item_id = int(item_id)
    except (TypeError, ValueError):
        return False

    cursor = execute(f"DELETE FROM {table} WHERE id = ?", (item_id,))

    get_db().commit()

    return cursor.rowcount > 0


def count(table, **criteria):
    validate_table(table)

    return sum(
        1
        for item in all_items(table)
        if all(item.get(key) == value for key, value in criteria.items())
    )


def upsert_by(table, key, value, payload):
    validate_table(table)

    existing = find_one(table, **{key: value})

    if existing:
        return update(table, existing["id"], payload)

    return insert(table, payload)
